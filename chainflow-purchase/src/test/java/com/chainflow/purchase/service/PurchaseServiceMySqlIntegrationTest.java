package com.chainflow.purchase.service;

import com.chainflow.purchase.PurchaseApplication;
import com.chainflow.purchase.api.PurchaseController.CreatePurchaseRequest;
import com.chainflow.purchase.model.PurchaseOrder;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Regression test for generated-key propagation against the real MySQL schema.
 * Run with CHAINFLOW_PURCHASE_IT=true while the local MySQL container exposes
 * port 13306 (the module's default datasource configuration).
 */
@EnabledIfEnvironmentVariable(named = "CHAINFLOW_PURCHASE_IT", matches = "true")
@SpringBootTest(classes = PurchaseApplication.class, webEnvironment = SpringBootTest.WebEnvironment.NONE)
class PurchaseServiceMySqlIntegrationTest {
    private static final String SUPPLIER = "IT-GENKEY-SUPPLIER";

    @Autowired
    private PurchaseService service;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @AfterEach
    void cleanUp() {
        jdbcTemplate.update("DELETE FROM purchase_order WHERE supplier_code = ?", SUPPLIER);
    }

    @Test
    void createPersistsAndReturnsAutoGeneratedId() {
        PurchaseOrder created = service.create(new CreatePurchaseRequest(SUPPLIER, "IT-GENKEY-SKU", 2));

        assertNotNull(created.id(), "the API response must contain MySQL's generated id");
        assertTrue(created.id() > 0);
        assertEquals(SUPPLIER, created.supplierCode());
        assertEquals("CREATED", created.status());

        Integer rows = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM purchase_order WHERE id = ? AND supplier_code = ? AND status = 'CREATED'",
                Integer.class, created.id(), SUPPLIER);
        assertEquals(1, rows);
    }
}
